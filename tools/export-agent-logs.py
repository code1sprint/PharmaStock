#!/usr/bin/env python3
"""Copy the day's AI agent sessions for this repo into 02-project/agent-logs/.

Reads the session logs that Claude Code, Codex, OpenCode and the DeepSeek
harness (dsh) keep on this computer, keeps the sessions that ran inside this
repo during the time window, hides likely secrets and writes one Markdown
transcript per session.

    python3 tools/export-agent-logs.py --since 09:00    # from 09:00 today until now
    python3 tools/export-agent-logs.py --dry-run        # only list what it finds

Read the files before you commit them. Sessions from other tools (Cursor, web
chats) need a manual Markdown export into the same folder.

Needs Python 3.8 or newer and nothing else. DeepSeek harness logs are zstd
files: they need Python 3.14+, the `zstandard` package or the `zstd` command.
"""

import argparse
import datetime as dt
import json
import os
import re
import shutil
import sqlite3
import subprocess
import sys
import tempfile
from pathlib import Path

MAX_TEXT = 4000  # characters kept of one message
MAX_TOOL = 240  # characters kept of one tool call
MAX_RESULT = 300  # characters kept of one tool result
MAX_FILE = 240 * 1024  # bytes per transcript; the middle is cut beyond this

# Likely secrets, replaced before anything is written. Each replacement keeps
# the word "redacted" so Reporter's secret scan treats it as a placeholder.
REDACT = [
    (re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY(?: BLOCK)?-----.*?(?:-----END [A-Z ]*PRIVATE KEY(?: BLOCK)?-----|\Z)", re.S), "[redacted private key]"),
    (re.compile(r"\b(sk|aag)-[A-Za-z0-9_\-]{20,}"), r"\1-[redacted]"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "[redacted aws key]"),
    (re.compile(r"\b(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|glpat-[A-Za-z0-9_\-]{20,}|xox[abprs]-[A-Za-z0-9\-]{10,})"), "[redacted token]"),
    (re.compile(r"\beyJ[A-Za-z0-9_\-]{8,}\.[A-Za-z0-9_\-]{8,}\.[A-Za-z0-9_\-]{8,}"), "[redacted jwt]"),
    (re.compile(r"(?i)\b(bearer|basic)(\s+)[A-Za-z0-9_\-.=+/]{12,}"), r"\1\2[redacted]"),
    (re.compile(r"(?i)\b([a-z][a-z0-9+.\-]*://[^\s:/@]+):[^\s@/]+@"), r"\1:[redacted]@"),
    (re.compile(r"""(?i)\b(password|passwd|pwd|secret|api[_-]?key|access[_-]?token|auth[_-]?token|token)\b(["']?\s*[:=]\s*["'])[^"'\s]{8,}(["'])"""), r"\1\2[redacted]\3"),
    (re.compile(r"(?m)^(\s*(?:export\s+)?[A-Z0-9_]*(?:PASSWORD|PASSWD|SECRET|TOKEN|API_KEY|APIKEY|ACCESS_KEY|PRIVATE_KEY)[A-Z0-9_]*\s*[=:]\s*)(?!\[redacted)\S{6,}"), r"\1[redacted]"),
]

# Context the tools inject as "user" messages; not typed by the person.
INJECTED_PREFIXES = (
    "<environment_context",
    "<user_instructions",
    "<permissions instructions",
    "# AGENTS.md instructions",
    "<local-command-stdout",
    "<local-command-stderr",
    "Caveat: The messages below were generated by the user",
)
WRAPPED = re.compile(r"^\s*<([A-Za-z_][\w-]*)[^>]*>.*</\1>\s*$", re.S)


def redact(text):
    for pattern, repl in REDACT:
        text = pattern.sub(repl, text)
    return text


def cut(text, limit):
    text = text.strip()
    return text if len(text) <= limit else text[:limit].rstrip() + " …[cut]"


def one_line(text, limit):
    return cut(re.sub(r"\s+", " ", text or ""), limit)


def injected(text):
    t = text.lstrip()
    return t.startswith(INJECTED_PREFIXES) or bool(WRAPPED.match(t))


def parse_iso(value):
    if not isinstance(value, str) or not value:
        return None
    s = value.strip().replace("Z", "+00:00")
    m = re.match(r"^(.*T\d\d:\d\d:\d\d)(?:\.(\d+))?(.*)$", s)
    if m:  # Python < 3.11 wants exactly 6 fraction digits
        frac = (m.group(2) or "0")[:6].ljust(6, "0")
        s = "%s.%s%s" % (m.group(1), frac, m.group(3))
    try:
        t = dt.datetime.fromisoformat(s)
    except ValueError:
        return None
    return t if t.tzinfo else t.replace(tzinfo=dt.timezone.utc)


def from_ms(value):
    if not isinstance(value, (int, float)) or value <= 0:
        return None
    return dt.datetime.fromtimestamp(value / 1000, tz=dt.timezone.utc)


def text_of(content):
    """Plain text of a string or a list of content blocks."""
    if content is None:
        return ""
    if isinstance(content, str):
        return content
    if isinstance(content, dict):
        content = [content]
    out = []
    for b in content if isinstance(content, list) else []:
        if isinstance(b, str):
            out.append(b)
        elif isinstance(b, dict):
            if isinstance(b.get("text"), str):
                out.append(b["text"])
            elif b.get("type") in ("image", "input_image", "image_url"):
                out.append("[image]")
            elif "content" in b:
                out.append(text_of(b["content"]))
    return "\n".join(x for x in out if x)


def tool_summary(name, args):
    """One line naming a tool call and its most telling argument."""
    if isinstance(args, str):
        try:
            args = json.loads(args)
        except ValueError:
            return "%s: %s" % (name, one_line(args, MAX_TOOL))
    if isinstance(args, dict):
        for key in ("command", "cmd", "file_path", "filePath", "path", "pattern", "url", "query", "description", "prompt"):
            v = args.get(key)
            if isinstance(v, list):
                v = " ".join(str(x) for x in v)
            if isinstance(v, str) and v.strip():
                return "%s: %s" % (name, one_line(v, MAX_TOOL))
        return "%s: %s" % (name, one_line(json.dumps(args, ensure_ascii=False), MAX_TOOL))
    return name or "tool"


class Session:
    def __init__(self, tool, sid):
        self.tool, self.id, self.cwd, self.title = tool, sid, None, ""
        self.models, self.entries = [], []

    def add(self, when, kind, text, model=None, error=False):
        if when is None or not (text or "").strip():
            return
        if model and model != "<synthetic>" and model not in self.models:
            self.models.append(model)
        self.entries.append((when, kind, text, error))


class Finder:
    def __init__(self, root, since, until):
        self.root = os.path.normcase(os.path.realpath(str(root)))
        self.since, self.until = since, until
        self.notes = []

    def inside(self, cwd):
        if not cwd:
            return False
        p = os.path.normcase(os.path.realpath(cwd))
        return p == self.root or p.startswith(self.root + os.sep)

    def in_window(self, when):
        return when is not None and self.since <= when <= self.until

    def recent(self, path):
        try:
            return dt.datetime.fromtimestamp(path.stat().st_mtime, tz=dt.timezone.utc) >= self.since
        except OSError:
            return False

    # Claude Code: ~/.claude/projects/<folder>/<session>.jsonl
    def claude(self):
        base = Path(os.environ.get("CLAUDE_CONFIG_DIR") or Path.home() / ".claude") / "projects"
        for f in sorted(base.glob("*/*.jsonl")):
            if not self.recent(f):
                continue
            s = Session("Claude Code", f.stem)
            for o in jsonl(f):
                if s.cwd is None and o.get("cwd"):
                    s.cwd = o["cwd"]
                    if not self.inside(s.cwd):
                        break
                kind = o.get("type")
                if kind == "ai-title" and o.get("aiTitle"):
                    s.title = o["aiTitle"]
                if kind not in ("user", "assistant") or o.get("isSidechain") or o.get("isMeta"):
                    continue
                when = parse_iso(o.get("timestamp"))
                if not self.in_window(when):
                    continue
                msg = o.get("message") or {}
                content = msg.get("content")
                if kind == "user":
                    if isinstance(content, str):
                        if not injected(content):
                            s.add(when, "user", content)
                        continue
                    for b in content or []:
                        if b.get("type") == "text" and not injected(b.get("text", "")):
                            s.add(when, "user", b.get("text", ""))
                        elif b.get("type") == "tool_result":
                            s.add(when, "result", text_of(b.get("content")), error=bool(b.get("is_error")))
                else:
                    for b in content or []:
                        if b.get("type") == "text":
                            s.add(when, "agent", b.get("text", ""), msg.get("model"))
                        elif b.get("type") == "tool_use":
                            s.add(when, "tool", tool_summary(b.get("name"), b.get("input")), msg.get("model"))
            if self.inside(s.cwd):
                yield s

    # Codex: ~/.codex/sessions/YYYY/MM/DD/rollout-*.jsonl
    def codex(self):
        base = Path(os.environ.get("CODEX_HOME") or Path.home() / ".codex") / "sessions"
        for f in sorted(base.rglob("*.jsonl")):
            if not self.recent(f):
                continue
            s = Session("Codex", f.stem)
            model = None
            for o in jsonl(f):
                kind, p = o.get("type"), o.get("payload")
                if not isinstance(p, dict):
                    continue
                if kind == "session_meta":
                    s.cwd, s.id = p.get("cwd"), p.get("id") or s.id
                    if not self.inside(s.cwd):
                        break
                    continue
                if kind == "turn_context":
                    model = p.get("model") or model
                    continue
                if kind != "response_item":
                    continue
                when = parse_iso(o.get("timestamp"))
                if not self.in_window(when):
                    continue
                pt = p.get("type")
                if pt == "message":
                    items = p.get("content") or []
                    if p.get("role") == "user":
                        typed = [text_of(i) for i in items if not injected(text_of(i))]
                        s.add(when, "user", "\n".join(typed))
                    elif p.get("role") == "assistant":
                        s.add(when, "agent", text_of(items), model)
                elif pt in ("function_call", "custom_tool_call", "local_shell_call"):
                    args = p.get("arguments") or p.get("input") or p.get("action")
                    s.add(when, "tool", tool_summary(p.get("name") or "shell", args), model)
                elif pt in ("function_call_output", "custom_tool_call_output"):
                    out, error = p.get("output"), False
                    if isinstance(out, str):
                        try:
                            parsed = json.loads(out)
                            if isinstance(parsed, dict) and "output" in parsed:
                                code = (parsed.get("metadata") or {}).get("exit_code")
                                out, error = parsed["output"], bool(code)
                        except ValueError:
                            pass
                    s.add(when, "result", text_of(out), error=error)
            if self.inside(s.cwd):
                yield s

    # DeepSeek harness: ~/.dsh/sessions/<folder>/session-<id>/session.jsonl.zstd
    def dsh(self):
        base = Path.home() / ".dsh" / "sessions"
        for f in sorted(base.glob("*/session-*/session.jsonl*")):
            if not self.recent(f):
                continue
            lines = read_maybe_zstd(f, self.notes)
            if lines is None:
                continue
            s = Session("DeepSeek harness", f.parent.name.replace("session-", "", 1))
            for o in jsonl_lines(lines):
                kind, d = o.get("type"), o.get("data") or {}
                if kind == "session":
                    s.cwd, s.id = o.get("cwd"), re.sub(r"^session-", "", o.get("id") or s.id)
                    if not self.inside(s.cwd) or (o.get("delegationDepth") or 0) > 0:
                        s.cwd = None  # someone else's folder, or a sub-agent
                        break
                    continue
                if kind == "session/title" and d.get("title"):
                    s.title = d["title"]
                when = from_ms(o.get("time"))
                if not self.in_window(when):
                    continue
                if kind == "user/message" and (d.get("source") or {}).get("kind") == "user":
                    s.add(when, "user", text_of(d.get("content")))
                elif kind == "assistant/message":
                    msg = d.get("message") or {}
                    model = (msg.get("source") or {}).get("model")
                    for b in msg.get("content") or []:
                        if b.get("type") == "text":
                            s.add(when, "agent", b.get("text", ""), model)
                        elif b.get("type") == "tool-call":
                            s.add(when, "tool", tool_summary(b.get("name"), b.get("arguments")), model)
                elif kind == "tool/result":
                    for b in (d.get("message") or {}).get("content") or []:
                        if b.get("type") == "tool-result":
                            s.add(when, "result", text_of(b.get("content")), error=bool(b.get("isError")))
            if self.inside(s.cwd):
                yield s

    # OpenCode: ~/.local/share/opencode/opencode*.db (SQLite)
    def opencode(self):
        base = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local" / "share") / "opencode"
        for db in sorted(base.glob("opencode*.db")):
            if not self.recent(db) and not self.recent(Path(str(db) + "-wal")):
                continue
            with tempfile.TemporaryDirectory() as tmp:
                # Read a copy so a running OpenCode is never locked out.
                copy = Path(tmp) / db.name
                for suffix in ("", "-wal", "-shm"):
                    src = Path(str(db) + suffix)
                    if src.exists():
                        shutil.copyfile(str(src), str(copy) + suffix)
                try:
                    con = sqlite3.connect(str(copy))
                    try:
                        for s in self._opencode_db(con):
                            yield s
                    finally:
                        con.close()
                except sqlite3.Error as e:
                    self.notes.append("OpenCode: could not read %s (%s)" % (db, e))

    def _opencode_db(self, con):
        since_ms = int(self.since.timestamp() * 1000)
        rows = con.execute(
            "SELECT id, directory, title, parent_id FROM session WHERE time_updated >= ? ORDER BY time_created", (since_ms,)
        ).fetchall()
        for sid, directory, title, parent in rows:
            if parent or not self.inside(directory):
                continue
            s = Session("OpenCode", sid)
            s.cwd, s.title = directory, title or ""
            parts = {}
            for mid, data in con.execute("SELECT message_id, data FROM part WHERE session_id = ? ORDER BY time_created, id", (sid,)):
                parts.setdefault(mid, []).append(load(data))
            for mid, created, data in con.execute("SELECT id, time_created, data FROM message WHERE session_id = ? ORDER BY time_created, id", (sid,)):
                msg = load(data)
                when = from_ms(created)
                if not self.in_window(when):
                    continue
                role, model = msg.get("role"), msg.get("modelID")
                for p in parts.get(mid, []):
                    pt = p.get("type")
                    if pt == "text" and not p.get("synthetic") and not p.get("ignored"):
                        s.add(when, "user" if role == "user" else "agent", p.get("text", ""), None if role == "user" else model)
                    elif pt == "tool":
                        state = p.get("state") or {}
                        s.add(when, "tool", tool_summary(p.get("tool"), state.get("input")), model)
                        if state.get("status") == "error":
                            s.add(when, "result", str(state.get("error") or "error"), error=True)
                        elif state.get("output"):
                            s.add(when, "result", text_of(state.get("output")))
            yield s


def load(data):
    try:
        v = json.loads(data)
        return v if isinstance(v, dict) else {}
    except (TypeError, ValueError):
        return {}


def jsonl(path):
    try:
        with open(str(path), encoding="utf-8", errors="replace") as fh:
            for o in jsonl_lines(fh):
                yield o
    except OSError:
        return


def jsonl_lines(lines):
    for line in lines:
        line = line.strip()
        if not line:
            continue
        try:
            o = json.loads(line)
        except ValueError:
            continue
        if isinstance(o, dict):
            yield o


def read_maybe_zstd(path, notes):
    if path.suffix != ".zstd":
        return path.read_text(encoding="utf-8", errors="replace").splitlines()
    raw = path.read_bytes()
    try:
        from compression import zstd  # Python 3.14+

        return zstd.decompress(raw).decode("utf-8", "replace").splitlines()
    except ImportError:
        pass
    try:
        import zstandard

        return zstandard.ZstdDecompressor().decompressobj().decompress(raw).decode("utf-8", "replace").splitlines()
    except ImportError:
        pass
    if shutil.which("zstd"):
        out = subprocess.run(["zstd", "-dcq", str(path)], stdout=subprocess.PIPE, check=False)
        if out.returncode == 0:
            return out.stdout.decode("utf-8", "replace").splitlines()
    msg = "DeepSeek harness: install zstd (brew install zstd / apt install zstd) or use Python 3.14+ to read its sessions"
    if msg not in notes:
        notes.append(msg)
    return None


def local(t):
    return t.astimezone().strftime("%H:%M")


def render(s, root, now):
    first, last = s.entries[0][0], s.entries[-1][0]
    try:
        folder = os.path.relpath(os.path.realpath(s.cwd), os.path.realpath(str(root)))
    except ValueError:
        folder = s.cwd
    head = [
        "# %s session %s" % (s.tool, short_id(s.id)),
        "",
        "- Tool: %s" % s.tool,
        "- Models: %s" % (", ".join(s.models) or "not recorded"),
        "- Folder: %s" % folder.replace(os.sep, "/"),
        "- Time: %s %s–%s, %d entries" % (first.astimezone().strftime("%Y-%m-%d"), local(first), local(last), len(s.entries)),
    ]
    if s.title:
        head.append("- Title: %s" % one_line(s.title, 200))
    head += [
        "- Exported %s by tools/export-agent-logs.py; likely secrets are replaced with [redacted]." % now.astimezone().strftime("%Y-%m-%d %H:%M"),
        "",
        "---",
        "",
    ]
    body = []
    for when, kind, text, error in s.entries:
        if kind == "user":
            body.append("\n### %s · You\n\n%s\n" % (local(when), cut(text, MAX_TEXT)))
        elif kind == "agent":
            body.append("\n### %s · Agent\n\n%s\n" % (local(when), cut(text, MAX_TEXT)))
        elif kind == "tool":
            body.append("- %s → %s" % (local(when), one_line(text, MAX_TOOL)))
        else:
            body.append("  - %s %s" % ("error:" if error else "result:", one_line(text, MAX_RESULT)))
    body = [redact(b) for b in body]
    size = sum(len(b.encode("utf-8")) + 1 for b in body)
    if size > MAX_FILE:  # keep the start and the end of a long session
        keep_head, keep_tail, used, i = [], [], 0, 0
        while i < len(body) and used < MAX_FILE * 0.4:
            used += len(body[i].encode("utf-8")) + 1
            keep_head.append(body[i])
            i += 1
        j = len(body)
        while j > i and used < MAX_FILE * 0.95:
            j -= 1
            used += len(body[j].encode("utf-8")) + 1
            keep_tail.insert(0, body[j])
        body = keep_head + ["\n… %d entries cut to keep the file small …\n" % (j - i)] + keep_tail
    return redact("\n".join(head)) + "\n" + "\n".join(body) + "\n"


def short_id(sid):
    return re.sub(r"[^A-Za-z0-9]", "", re.sub(r"^(?:ses|session)[-_]", "", sid))[:8]


def slug(tool):
    return {"Claude Code": "claude", "Codex": "codex", "OpenCode": "opencode", "DeepSeek harness": "dsh"}.get(tool, "agent")


def parse_when(value, day, default):
    if not value:
        return default
    for fmt in ("%H:%M", "%Y-%m-%d %H:%M", "%Y-%m-%dT%H:%M"):
        try:
            t = dt.datetime.strptime(value, fmt)
        except ValueError:
            continue
        if fmt == "%H:%M":
            t = dt.datetime.combine(day, t.time())
        return t.astimezone()
    sys.exit("could not read the time %r; use HH:MM or YYYY-MM-DD HH:MM" % value)


def main():
    here = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description="Copy the day's agent sessions for this repo into 02-project/agent-logs/.")
    ap.add_argument("--since", help="start of the window, HH:MM today or YYYY-MM-DD HH:MM (default: today 00:00)")
    ap.add_argument("--until", help="end of the window (default: now)")
    ap.add_argument("--date", help="the day for HH:MM times, YYYY-MM-DD (default: today)")
    ap.add_argument("--repo", default=str(here), help="repo folder (default: the one this script is in)")
    ap.add_argument("--out", help="output folder (default: <repo>/02-project/agent-logs)")
    ap.add_argument("--dry-run", action="store_true", help="list the sessions, write nothing")
    a = ap.parse_args()

    now = dt.datetime.now().astimezone()
    day = dt.date.fromisoformat(a.date) if a.date else now.date()
    since = parse_when(a.since, day, dt.datetime.combine(day, dt.time()).astimezone())
    until = parse_when(a.until, day, now)
    if until <= since:
        sys.exit("--until must be after --since")
    root = Path(a.repo).resolve()
    out = Path(a.out) if a.out else root / "02-project" / "agent-logs"

    finder = Finder(root, since, until)
    sessions = []
    for name, source in (("Claude Code", finder.claude), ("Codex", finder.codex), ("OpenCode", finder.opencode), ("DeepSeek harness", finder.dsh)):
        try:
            found = [s for s in source() if s.entries]
        except Exception as e:  # one broken tool must not stop the others
            finder.notes.append("%s: skipped (%s: %s)" % (name, type(e).__name__, e))
            continue
        sessions += found

    print("Window: %s → %s" % (since.strftime("%Y-%m-%d %H:%M"), until.strftime("%Y-%m-%d %H:%M")))
    print("Repo:   %s" % root)
    if not sessions:
        print("No agent sessions found in this repo during the window.")
    if not a.dry_run and sessions:
        out.mkdir(parents=True, exist_ok=True)
    for s in sorted(sessions, key=lambda s: s.entries[0][0]):
        first = s.entries[0][0].astimezone()
        name = "%s-%s-%s.md" % (first.strftime("%Y-%m-%d-%H%M"), slug(s.tool), short_id(s.id))
        print("  %-17s %s–%s %4d entries  %s" % (s.tool, local(s.entries[0][0]), local(s.entries[-1][0]), len(s.entries), name))
        if not a.dry_run:
            (out / name).write_text(render(s, root, now), encoding="utf-8")
    for n in finder.notes:
        print("Note: " + n)
    if sessions and not a.dry_run:
        print("Wrote %d file(s) to %s. Read them, delete anything private, then commit." % (len(sessions), out))
    print("Cursor or web chats are not covered: export them to Markdown by hand into the same folder.")


if __name__ == "__main__":
    main()
